@pytest.mark.skipif(os.name != "posix", reason="file modes are a POSIX concept")
def test_group_or_world_readable_key_logs_a_warning(
    cert_pair: tuple[Path, Path], caplog: pytest.LogCaptureFixture
) -> None:
    cert_path, key_path = cert_pair
    key_path.chmod(0o644)
    with caplog.at_level(logging.WARNING, logger="lenguaraz.config"):
        Settings(_env_file=None, engine="fake", tls_cert_file=cert_path, tls_key_file=key_path)
    assert "readable by group/others" in caplog.text
    caplog.clear()
    key_path.chmod(0o600)
    with caplog.at_level(logging.WARNING, logger="lenguaraz.config"):
        Settings(_env_file=None, engine="fake", tls_cert_file=cert_path, tls_key_file=key_path)
    assert "readable by group/others" not in caplog.text


