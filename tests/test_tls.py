# --------------------------------------------------------------------- FR-013-04: the script


def test_selfsigned_certificate_covers_localhost_and_loopback(cert_pair: tuple[Path, Path]) -> None:
    cert_path, key_path = cert_pair
    certificate = x509.load_pem_x509_certificate(cert_path.read_bytes())
    san = certificate.extensions.get_extension_for_class(x509.SubjectAlternativeName).value
    assert san.get_values_for_type(x509.DNSName) == ["localhost"]
    assert {str(ip) for ip in san.get_values_for_type(x509.IPAddress)} == {"127.0.0.1", "::1"}
    lifetime = certificate.not_valid_after_utc - certificate.not_valid_before_utc
    assert 824 <= lifetime.days <= 826
    assert certificate.issuer == certificate.subject  # self-signed
    assert key_path.read_text(encoding="ascii").startswith("-----BEGIN PRIVATE KEY-----")
    if os.name == "posix":
        assert (key_path.stat().st_mode & 0o777) == 0o600


def test_script_main_writes_into_the_requested_folder(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    argv = ["--dir", str(tmp_path / "certs"), "--hostname", "captions.local"]
    assert selfsigned_cert.main(argv) == 0
    assert (tmp_path / "certs" / "dev-cert.pem").is_file()
    assert (tmp_path / "certs" / "dev-key.pem").is_file()
    out = capsys.readouterr().out
    assert "never for production" in out
    assert "TLS_CERT_FILE=" in out


